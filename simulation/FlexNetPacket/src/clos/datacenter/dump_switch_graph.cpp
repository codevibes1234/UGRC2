
#include "graph_gen.h"
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <iostream>
#include <set>
#include <string>

int main(int argc, char **argv)
{
    if (argc < 3) {
        std::cerr << "usage: " << argv[0]
                  << " <jellyfish|flatbutterfly|dragonfly|megafly> <nhost> [outfile]\n";
        return 1;
    }
    std::string family = argv[1];
    int nhost = atoi(argv[2]);

    SwitchGraph g = make_named(family, nhost);
    if (g.nsw == 0) {
        std::cerr << "ERROR: unknown family '" << family << "'\n";
        return 1;
    }

    std::ostream *os = &std::cout;
    std::ofstream f;
    if (argc >= 4) {
        f.open(argv[3]);
        if (!f) { std::cerr << "ERROR: cannot write " << argv[3] << "\n"; return 1; }
        os = &f;
    }

    *os << "# generated by dump_switch_graph " << family << " " << nhost << "\n";
    *os << "name " << g.name << "\n";
    *os << "nhost " << g.nhost << "\n";
    *os << "nsw " << g.nsw << "\n";
    *os << "host_ports " << g.host_ports << "\n";

    for (int h = 0; h < g.nhost; h++)
        *os << "host " << h << " " << g.host_switch[h] << "\n";

    std::set<std::pair<int, int>> seen;
    long nlink = 0;
    for (int s = 0; s < g.nsw; s++)
        for (int t : g.adj[s]) {
            auto key = std::make_pair(std::min(s, t), std::max(s, t));
            if (seen.insert(key).second) { *os << "link " << key.first << " " << key.second << "\n"; nlink++; }
        }

    std::cerr << family << ": " << g.nhost << " hosts, " << g.nsw << " switches, "
              << nlink << " links  (" << g.name << ")\n";
    return 0;
}
